"""Bake a land/ocean bitmask for the 3D globe scenes.

Reads the equirectangular Natural Earth outline that already ships in
_includes/world-land.html (coordinate space x = lon + 180, y = 90 - lat) and
rasterises it to a W x H bit grid, packed MSB-first and base64-encoded.

The globe scenes scatter points over a sphere and keep the ones that land on
a set bit, so the mask only has to be good enough to read as the continents
at a few hundred pixels across.

    python scripts/build_landmask.py

Writes assets/js/world-mask.js.
"""

import base64
import pathlib
import re

W, H = 240, 120
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "_includes" / "world-land.html"
OUT = ROOT / "assets" / "js" / "world-mask.js"


def rings():
    """Every closed ring in the baked path, as lists of (x, y) in path space."""
    d = re.search(r'\sd="([^"]+)"', SRC.read_text(encoding="utf-8")).group(1)
    out = []
    for chunk in d.split("M"):
        chunk = chunk.strip().rstrip("Zz")
        if not chunk:
            continue
        pts = []
        for pair in chunk.replace("Z", " ").split():
            x, _, y = pair.partition(",")
            pts.append((float(x), float(y)))
        if len(pts) >= 3:
            out.append(pts)
    return out


def rasterise(polys):
    grid = bytearray(W * H)

    # Scanline fill, even-odd so that inner rings read as holes.
    for j in range(H):
        y = (j + 0.5) * (180.0 / H)
        xs = []
        for ring in polys:
            for k in range(len(ring)):
                x1, y1 = ring[k]
                x2, y2 = ring[(k + 1) % len(ring)]
                if y1 == y2:
                    continue
                if (y1 <= y < y2) or (y2 <= y < y1):
                    xs.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
        xs.sort()
        for a, b in zip(xs[::2], xs[1::2]):
            i0 = max(0, int(a / (360.0 / W)))
            i1 = min(W - 1, int(b / (360.0 / W)))
            for i in range(i0, i1 + 1):
                grid[j * W + i] = 1

    # Islands smaller than a cell fall through the scanline, so stamp every
    # vertex too. Coastlines come out a touch fat; at this scale that reads
    # better than a Pacific with nothing in it.
    for ring in polys:
        for x, y in ring:
            i = min(W - 1, max(0, int(x / (360.0 / W))))
            j = min(H - 1, max(0, int(y / (180.0 / H))))
            grid[j * W + i] = 1

    return grid


def main():
    polys = rings()
    grid = rasterise(polys)
    packed = bytearray((W * H + 7) // 8)
    for k, v in enumerate(grid):
        if v:
            packed[k >> 3] |= 1 << (7 - (k & 7))
    b64 = base64.b64encode(bytes(packed)).decode("ascii")
    OUT.write_text(
        "/* Generated by scripts/build_landmask.py - do not edit by hand.\n"
        "   Natural Earth 1:110m land, rasterised to a %d x %d bit grid,\n"
        "   packed MSB-first. Consumed by assets/js/orbital.js. */\n"
        'window.VM_LANDMASK = "%s";\n' % (W, H, b64),
        encoding="utf-8",
    )
    land = sum(grid)
    print("rings            %d" % len(polys))
    print("grid             %dx%d" % (W, H))
    print("land cells       %d (%.1f%%)" % (land, 100.0 * land / (W * H)))
    print("base64           %d bytes" % len(b64))
    print("wrote            %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
